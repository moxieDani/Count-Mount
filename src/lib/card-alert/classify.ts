// 가맹점 이름 → 계정(분류). purchase_name_to_classification.py 를 옮긴 것.
// 원본과 다른 점: 이마트에브리데이가 장보기로 빠지던 문제 수정
//   - `이마트(?!에브리데이)?` 의 끝 `?` 제거 (JS u 플래그에서는 문법 오류)
//   - 장보기의 `마트` 가 이마트에브리데이를 먼저 잡으므로 생필품 규칙을 장보기 앞으로 이동
const CLASSIFICATION_RULES: [RegExp, string][] = [
	[/주유|정유|에너지|오일|LPG충전|가스충전/, '주유'],
	[/주차장|파킹|주차/, '주차'],
	[/하이패스|톨게이트|한국도로공사/, '하이패스'],
	[/정비|공업사|세차|타이어|블랙박스|현대서비스|기아서비스/, '자동차 기타'],
	[/건강검진|의학연구소|건강관리협회|KMI/, '예방(건강검진)'],
	[/병원|의원|약국|내과|외과|치과|안과|이비인후과|정형외과|한의원|의료법인|종합병원|대학병원/, '치료(병원,약국)'],
	[/배달의민족|쿠팡이츠|요기요|땡겨요/, '배달'],
	[/식당|카페|스타벅스|커피|맥도날드|롯데리아|버거킹|한식|중식|일식|양식|고깃집|갈비|뷔페|레스토랑|치킨|피자|족발/, '외식'],
	[/다이소|이마트에브리데이|GS THE FRESH|롯데슈퍼/, '생필품'],
	[/이마트(?!에브리데이)|롯데마트|홈플러스|코스트코|농협하나로|노브랜드|식자재|수퍼|마트|시장/, '장보기(식재료)'],
	[/CGV|메가박스|롯데시네마|영화관|교보문고|영풍문고|예스24|알라딘|서점|공연장|미술관/, '문화생활'],
	[/호텔|리조트|펜션|모텔|야놀자|여기어때|여행사|항공|티비티/, '여행'],
	[/헤어|미용실|뷰티|올리브영|네일|화장품|피부관리/, '미용/화장'],
	[/코레일|SRT|고속버스|티머니|카카오T|승차권/, '기타(기차예매 등)']
];

export function classifyMerchant(name: string | null | undefined): string | null {
	if (!name) return null;
	const cleaned = name.trim();
	for (const [pattern, category] of CLASSIFICATION_RULES) {
		if (pattern.test(cleaned)) return category;
	}
	return null;
}
